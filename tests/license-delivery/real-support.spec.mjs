import { expect } from '@playwright/test'
import { test, ownerLogin, memberLogin, createMember, createKey, captureFailures } from './real-fixtures.mjs'

test.use({ seedModels: true, actionTimeout: 10_000 })

function responseFor(page, path, method = 'GET', query = () => true) {
  return page.waitForResponse(response => {
    const url = new URL(response.url())
    return url.pathname === path && response.request().method() === method && query(url.searchParams)
  })
}
async function select(page, name, option) {
  await page.getByRole('combobox', { name, exact: true }).click()
  await page.getByRole('option', { name: option, exact: true }).click()
}
async function signIn(page, baseURL, kind, email, password) {
  await page.goto(`${baseURL}/login`)
  await page.getByLabel(kind === 'admin' ? '管理员邮箱' : '成员邮箱', { exact: true }).fill(email)
  await page.getByLabel('密码', { exact: true }).fill(password)
  const response = responseFor(page, `/api/${kind}/auth/login`, 'POST')
  await page.getByRole('button', { name: kind === 'admin' ? '进入管理端' : '进入用户端', exact: true }).click()
  expect((await response).status()).toBe(200)
}
async function changePassword(page, baseURL, kind, current, next) {
  await page.goto(`${baseURL}/account/password`)
  await page.getByLabel('当前密码', { exact: true }).fill(current)
  await page.getByLabel('新密码', { exact: true }).fill(next)
  await page.getByLabel('确认新密码', { exact: true }).fill(next)
  const response = responseFor(page, `/api/${kind}/auth/password`, 'POST')
  await page.getByRole('button', { name: '修改密码', exact: true }).click()
  expect((await response).status()).toBe(200)
  await expect(page).toHaveURL(/\/login(?:\?|$)/)
}

