    await page.getByRole('spinbutton', { name: /^用量结算倍率/ }).fill('1.25')
    const saved = responseFor(page, '/api/admin/settings', 'PUT')
    await page.getByRole('button', { name: '保存运行配置', exact: true }).click()
    expect((await saved).status()).toBe(200)
    await page.reload()
    await expect(page.getByRole('textbox', { name: /^公共 API 基础地址/ })).toHaveValue(publicURL)
    await expect(page.getByRole('spinbutton', { name: /^用量结算倍率/ })).toHaveValue('1.25')
    const documentation = responseFor(member, '/api/member/docs')
    await member.goto(`${backend.member_url}/docs`)
    const docsResponse = await documentation
