    const docs = await docsResponse.json()
    expect(docs.usage_multiplier).toBe(1.25)
    expect(docs.base_urls.openai).toBe(`${publicURL}/v1`)
    await expect(member.locator('.a-copy-code').filter({ hasText: publicURL }).first()).toBeVisible()

