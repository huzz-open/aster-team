import { readFileSync } from 'node:fs'
import { basename, dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parse } from 'yaml'
import openapiTS, { astToString } from 'openapi-typescript'
import Ajv2020 from 'ajv/dist/2020.js'
import standaloneCode from 'ajv/dist/standalone/index.js'

const schemaRoot = resolve(dirname(fileURLToPath(import.meta.url)), '../../contracts/schemas')

// Traverse only the reachable public payload, never ship the approval/order
// definitions that happen to live in the same source schema.
export function publicSchema(filename, fragment = '', overrides = new Map()) {
  const documents = new Map()
  function document(path) {
    if (!documents.has(path)) documents.set(path, parse(overrides.get(`contracts/schemas/${basename(path)}`) ?? readFileSync(path, 'utf8')))
    return documents.get(path)
  }
  function expand(value, path, stack) {
    if (Array.isArray(value)) return value.map(item => expand(item, path, stack))
    if (typeof value !== 'object' || value === null) return value
    const siblings = Object.fromEntries(Object.entries(value)
      .filter(([key]) => !['$id', '$schema', '$defs', '$ref'].includes(key))
      .map(([key, child]) => [key, expand(child, path, stack)]))
    if (!value.$ref) return siblings
    const [file, pointer = ''] = value.$ref.split('#')
    if (file && !/^[a-z0-9.-]+\.schema\.yaml$/.test(file)) throw new Error('non-local public schema reference')
    const targetPath = file ? resolve(schemaRoot, file) : path
    const identity = `${targetPath}#${pointer}`
    if (stack.includes(identity)) throw new Error('cyclic public schema reference')
    let target = document(targetPath)
    if (pointer && !pointer.startsWith('/')) throw new Error('unsupported schema pointer')
    for (const token of pointer.split('/').slice(1)) target = target?.[token.replaceAll('~1', '/').replaceAll('~0', '~')]
    if (target === undefined) throw new Error(`missing public schema reference ${value.$ref}`)
    const expanded = expand(target, targetPath, [...stack, identity])
    if (Object.keys(siblings).every(key => ['title', 'description'].includes(key))) return { ...expanded, ...siblings }
    return Object.keys(siblings).length ? { allOf: [expanded, siblings] } : expanded
  }
  const path = resolve(schemaRoot, filename)
  return expand({ $ref: `#${fragment}` }, path, [])
}

export async function websiteContractOutputs(overrides = new Map()) {
  const catalog = publicSchema('public-catalog.v1.schema.yaml', '', overrides)
  const inquiry = publicSchema('product-inquiry.v1.schema.yaml', '', overrides)
  const reference = publicSchema('product-inquiry.v1.schema.yaml', '/$defs/reference', overrides)
  const response = publicSchema('product-inquiry.v1.schema.yaml', '/$defs/response', overrides)
  const ast = await openapiTS({
    openapi: '3.1.0', info: { title: 'Aster public website contracts', version: '1' }, paths: {},
    components: { schemas: { PublicCatalog: catalog, ProductInquiry: inquiry, InquiryReference: reference, InquiryResponse: response } },
  }, { alphabetize: true })
  const ajv = new Ajv2020({ strict: true, allErrors: false, code: { source: true, esm: true, lines: true } })
  const validator = ajv.compile(inquiry)
  // Keep JSON Schema code-point lengths, with no CommonJS runtime dependency
  // in the Worker/browser ESM validator. Payload size is bounded by the handler.
  const validatorSource = standaloneCode(ajv, validator)
    .replaceAll('require("ajv/dist/runtime/ucs2length").default', '((value) => [...value].length)')
  if (validatorSource.includes('require(')) throw new Error('unsupported standalone validator dependency')
  const header = '// @generated by tools/codegen/generate-contracts.mjs; DO NOT EDIT.\n'
  return new Map([
    ['website/shared/generated/contracts.ts', `${header}${astToString(ast)}\nexport type PublicCatalog = components['schemas']['PublicCatalog']\nexport type PublicPlan = PublicCatalog['plans'][number]\nexport type ProductInquiry = components['schemas']['ProductInquiry']\nexport type InquiryReference = components['schemas']['InquiryReference']\nexport type InquiryResponse = components['schemas']['InquiryResponse']\n`],
    ['website/shared/generated/inquiry-validator.js', `${header}${validatorSource.trimEnd()}\n`],
    ['website/shared/generated/inquiry-validator.d.ts', `${header}import type { ProductInquiry } from './contracts'\nexport default function validate(value: unknown): value is ProductInquiry\n`],
    ['website/shared/generated/public-catalog.schema.json', `${JSON.stringify(catalog, null, 2)}\n`],
  ])
}
