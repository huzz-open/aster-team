import { spawnSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { resolveGoCommand } from '../toolchains/go-toolchain.mjs'
import { parse } from 'yaml'
import { productCatalogOutputs } from './product-capabilities.mjs'
import { websiteContractOutputs } from './website-contracts.mjs'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const catalogPath = resolve(root, 'contracts/catalogs/error-codes.yaml')

function loadCatalog() {
  const catalog = parse(readFileSync(catalogPath, 'utf8'))
  if (catalog?.version !== 1 || !Array.isArray(catalog.errors) || catalog.errors.length === 0) {
    throw new Error('error-codes.yaml must contain a non-empty version 1 registry')
  }
  const codes = new Set()
  const numbers = new Set()
  for (const [index, entry] of catalog.errors.entries()) {
    if (!['customer', 'operations'].includes(entry?.target)) throw new Error(`errors[${index}].target is invalid`)
    if (!/^[A-Z][A-Z0-9_]+$/.test(entry.code || '')) throw new Error(`errors[${index}].code is invalid`)
    if (!Number.isSafeInteger(entry.number) || entry.number < 10_000 || entry.number > 99_999) {
      throw new Error(`errors[${index}].number must be a five-digit integer`)
    }
    if (codes.has(entry.code)) throw new Error(`duplicate error code ${entry.code}`)
    if (numbers.has(entry.number)) throw new Error(`duplicate error number ${entry.number}`)
    codes.add(entry.code)
    numbers.add(entry.number)
    if (entry.target === 'customer') {
      if (!/^[a-z][a-z0-9_]*$/.test(entry.module || '')) throw new Error(`${entry.code}.module is invalid`)
      if (!/^[A-Z][A-Z0-9_]*$/.test(entry.constant || '')) throw new Error(`${entry.code}.constant is invalid`)
      if (typeof entry.message !== 'string' || entry.message.length === 0) throw new Error(`${entry.code}.message is required`)
    }
  }
  return catalog.errors
}

function rustNumber(value) {
  const digits = String(value)
  return `${digits.slice(0, 2)}_${digits.slice(2)}`
}

function rustSource(entries) {
  const customer = entries.filter(entry => entry.target === 'customer')
  const modules = new Map()
  for (const entry of customer) {
    if (!modules.has(entry.module)) modules.set(entry.module, [])
    modules.get(entry.module).push(entry)
  }
  const lines = [
    '// @generated by tools/codegen/generate-contracts.mjs; DO NOT EDIT.',
    '#![forbid(unsafe_code)]',
    '',
    'use serde::Serialize;',
    '',
    '#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize)]',
    'pub struct ErrorDescriptor {',
    "    pub code: &'static str,",
    '    pub number: u32,',
    "    pub default_message: &'static str,",
    '}',
    '',
    'impl ErrorDescriptor {',
    "    pub const fn new(code: &'static str, number: u32, default_message: &'static str) -> Self {",
    '        assert!(number >= 10_000 && number <= 99_999);',
    '        Self {',
    '            code,',
    '            number,',
    '            default_message,',
    '        }',
    '    }',
    '}',
    '',
  ]
  for (const [module, moduleEntries] of modules) {
    lines.push(`pub mod ${module} {`, '    use super::ErrorDescriptor;', '')
    for (const entry of moduleEntries) {
      lines.push(
        `    pub const ${entry.constant}: ErrorDescriptor = ErrorDescriptor::new(`,
        `        ${JSON.stringify(entry.code)},`,
        `        ${rustNumber(entry.number)},`,
        `        ${JSON.stringify(entry.message)},`,
        '    );',
      )
    }
    lines.push('}', '')
  }
  lines.push('pub const ALL: &[ErrorDescriptor] = &[', ...customer.map(entry => `    ${entry.module}::${entry.constant},`), '];', '')
  lines.push(
    '#[cfg(test)]',
    'mod tests {',
    '    use std::collections::BTreeSet;',
    '',
    '    use super::ALL;',
    '',
    '    #[test]',
    '    fn published_numbers_and_codes_are_stable_and_unique() {',
    '        let numbers: BTreeSet<_> = ALL.iter().map(|entry| entry.number).collect();',
    '        let codes: BTreeSet<_> = ALL.iter().map(|entry| entry.code).collect();',
    '        assert_eq!(numbers.len(), ALL.len());',
    '        assert_eq!(codes.len(), ALL.len());',
    '        assert!(ALL.iter().all(|entry| (10_000..=99_999).contains(&entry.number)));',
    '    }',
    '}',
    '',
  )
  return `${lines.join('\n')}`
}

function goSource(entries) {
  const operations = entries.filter(entry => entry.target === 'operations')
  const source = [
    '// Code generated by tools/codegen/generate-contracts.mjs; DO NOT EDIT.',
    '',
    'package apierrors',
    '',
    'var codeNumbers = map[string]int64{',
    ...operations.map(entry => `\t${JSON.stringify(entry.code)}: ${entry.number},`),
    '}',
    '',
  ].join('\n')
  return formatGo(source)
}

function formatGo(source) {
  const result = spawnSync(resolveGoCommand('gofmt', root), [], { input: source, encoding: 'utf8' })
  if (result.error?.code === 'ENOENT') {
    throw new Error([
      'Missing required command: gofmt.',
      'npm ci installs Node.js dependencies only.',
      'From the repository directory, run the interactive installer: npm run setup',
    ].join('\n'))
  }
  if (result.error || result.status !== 0) {
    throw new Error(result.stderr || result.error?.message || 'gofmt failed for generated error catalog')
  }
  return result.stdout
}

function formatRust(source) {
  const result = spawnSync('rustfmt', ['--emit', 'stdout', '--edition', '2024'], { input: source, encoding: 'utf8' })
  if (result.error?.code === 'ENOENT') {
    throw new Error('Missing required command: rustfmt. Install Rust through rustup and run: rustup component add rustfmt')
  }
  if (result.error || result.status !== 0) {
    throw new Error(result.stderr || result.error?.message || 'rustfmt failed for generated error catalog')
  }
  return result.stdout
}

function typeScriptSource(entries, target) {
  const selected = entries.filter(entry => entry.target === target)
  return [
    '// @generated by tools/codegen/generate-contracts.mjs; DO NOT EDIT.',
    'export const ERROR_NUMBERS = {',
    ...selected.map(entry => `  ${entry.code}: ${entry.number},`),
    '} as const',
    '',
    'export type ErrorCode = keyof typeof ERROR_NUMBERS',
    'export type ErrorNumber = (typeof ERROR_NUMBERS)[ErrorCode]',
    '',
  ].join('\n')
}

function outputs(entries) {
  return new Map([
    ['customer/backend/crates/error-catalog/src/lib.rs', formatRust(rustSource(entries))],
    ['operations/backend/internal/apierrors/catalog_generated.go', goSource(entries)],
    ['customer/sdk/src/generated/error-codes.ts', typeScriptSource(entries, 'customer')],
    ['operations/console/src/api/generated/error-codes.ts', typeScriptSource(entries, 'operations')],
  ])
}

export function generatedContentsMatch(actual, expected) {
  const normalizeLineEndings = value => value.replace(/\r\n?/g, '\n')
  return normalizeLineEndings(actual) === normalizeLineEndings(expected)
}

async function main() {
  const check = process.argv.includes('--check')
  const generated = outputs(loadCatalog())
  const product = parse(readFileSync(resolve(root, 'contracts/catalogs/product-capabilities.yaml'), 'utf8'))
  for (const [path, source] of productCatalogOutputs(product)) {
    generated.set(path, path.endsWith('.rs') ? formatRust(source) : path.endsWith('.go') ? formatGo(source) : source)
  }
  for (const [path, source] of await websiteContractOutputs(generated)) generated.set(path, source)
  const stale = []
  for (const [relativePath, contents] of generated) {
    const path = resolve(root, relativePath)
    if (check) {
      if (!existsSync(path) || !generatedContentsMatch(readFileSync(path, 'utf8'), contents)) stale.push(relativePath)
      continue
    }
    mkdirSync(dirname(path), { recursive: true })
    writeFileSync(path, contents)
    console.log(`generated ${relativePath}`)
  }
  if (stale.length) throw new Error(`generated contract outputs are stale:\n${stale.join('\n')}`)
}

const entryPoint = process.argv[1] ? pathToFileURL(resolve(process.argv[1])).href : ''
if (import.meta.url === entryPoint) await main()
