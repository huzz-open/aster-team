import { spawnSync } from 'node:child_process'
import { randomUUID } from 'node:crypto'
import { readFileSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, resolve } from 'node:path'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const website = resolve(root, 'website')
const require = createRequire(resolve(website, 'package.json'))
const wrangler = resolve(dirname(require.resolve('wrangler/package.json')), 'bin/wrangler.js')
const generated = resolve(tmpdir(), `aster-worker-types-${process.pid}-${randomUUID()}.d.ts`)
// Wrangler embeds the chosen output path and a few trailing spaces in generated text.
// Compare the binding and runtime types while retaining the configuration hash.
const normalized = content => content.replace(/\r\n/g, '\n').replace(/[ \t]+(?=\n)/g, '')
  .replace(/^\/\/ Generated by Wrangler by running `[^`]+` \(hash: ([a-f0-9]+)\)$/m, '// Generated by Wrangler (hash: $1)')

try {
  const result = spawnSync(process.execPath, [wrangler, 'types', generated, '--env-file', '.dev.vars.example'], {
    cwd: website, stdio: 'inherit', windowsHide: true,
  })
  if (result.error) throw result.error
  if (result.status !== 0) process.exitCode = result.status ?? 1
  else if (normalized(readFileSync(generated, 'utf8')) !== normalized(readFileSync(resolve(website, 'worker-configuration.d.ts'), 'utf8'))) {
    const actual = normalized(readFileSync(generated, 'utf8')).split('\n')
    const tracked = normalized(readFileSync(resolve(website, 'worker-configuration.d.ts'), 'utf8')).split('\n')
    const firstDifference = actual.findIndex((line, index) => line !== tracked[index])
    console.error(`First difference at line ${firstDifference + 1}: generated ${JSON.stringify(actual[firstDifference])}, tracked ${JSON.stringify(tracked[firstDifference])}`)
    console.error('Cloudflare binding types are out of date. Run npm run cf:types --workspace @aster/website, then review worker-configuration.d.ts.')
    process.exitCode = 1
  } else console.log('Cloudflare binding types are current.')
} finally {
  rmSync(generated, { force: true })
}
